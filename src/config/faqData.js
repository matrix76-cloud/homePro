/** 검색 — 질문·답변·키워드·카테고리명을 공백 구분 AND 매칭 */
export function searchFaq(items, keyword) {
    const terms = (keyword || "").trim().toLowerCase().split(/\s+/).filter(Boolean);
    if (!terms.length) return items;
    return items.filter((item) => {
        const label = FAQ_CATEGORIES.find((c) => c.id === item.category)?.label || "";
        const haystack = [item.q, item.a, label, ...(item.keywords || [])].join(" ").toLowerCase();
        return terms.every((t) => haystack.includes(t));
    });
}
